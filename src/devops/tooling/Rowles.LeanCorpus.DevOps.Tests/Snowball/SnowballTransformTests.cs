using Rowles.LeanCorpus.DevOps.Snowball;

namespace Rowles.LeanCorpus.DevOps.Tests.Snowball;

public sealed class SnowballTransformTests
{
    private const string Licence = "Copyright (c) 2001, Dr Martin Porter\n\nAll rights reserved.\n";

    private const string Minimal = """
        // Generated from german.sbl by Snowball 3.2.0 - https://snowballstem.org/

        namespace Snowball
        {
            using System;
            using System.Text;

            public partial class GermanStemmer : Stemmer
            {
                private static readonly Among[] a_0 = new[]
                {
                    new Among("a", -1, 1, 0)
                };

                protected override bool stem()
                {
                    find_among_b(a_0, null);
                    return true;
                }
            }
        }
        """;

    [Fact]
    public void PinnedReferences_TransformWithOnlyTheListedRewrites()
    {
        var workspace = new SnowballWorkspace(FindRepositoryRoot());
        var manifest = SnowballFixtureManifest.Load(workspace.FixtureRoot);
        string licence = File.ReadAllText(Path.Combine(workspace.FixtureRoot, "LICENSE-snowball.txt"));
        int findAmong = 0;
        foreach (var algorithm in manifest.Algorithms)
        {
            string reference = File.ReadAllText(Path.Combine(workspace.FixtureRoot, algorithm.Reference));
            var first = SnowballTransform.Transform(algorithm.Name, reference, algorithm.SblSha256, licence);
            var second = SnowballTransform.Transform(algorithm.Name, reference, algorithm.SblSha256, licence);

            Assert.Equal(first.Source, second.Source);
            Assert.Equal(1, first.Counts.Namespace);
            Assert.Equal(1, first.Counts.ClassDeclaration);
            Assert.StartsWith("// <auto-generated/>\n", first.Source, StringComparison.Ordinal);
            Assert.Contains("Copyright (c) 2001, Dr Martin Porter", first.Source, StringComparison.Ordinal);
            Assert.Contains($"internal sealed class {SnowballTransform.ClassName(algorithm.Name)} : SnowballRuntime", first.Source, StringComparison.Ordinal);
            Assert.Equal(first.BodySha256, SnowballTransform.BodySha256(first.Source));
            Assert.Equal(algorithm.Name == "arabic" ? 35 : 0, first.Counts.CurrentLength);
            Assert.Equal(algorithm.Name == "dutch" ? 3 : 0, first.Counts.Slices);
            Assert.Equal(algorithm.Name == "dutch", first.Source.Contains("protected override void ResetState()", StringComparison.Ordinal));
            findAmong += first.Counts.FindAmongCalls;
        }

        // Every find_among call in the nine pinned algorithms passes a null condition callback.
        Assert.Equal(94, findAmong);
    }

    [Fact]
    public void CommittedOutput_IsCurrent()
    {
        var problems = new SnowballWorkspace(FindRepositoryRoot()).Verify();
        Assert.True(problems.Count == 0, string.Join(Environment.NewLine, problems));
    }

    [Fact]
    public void Minimal_TransformsToTheProductionShape()
    {
        var result = SnowballTransform.Transform("german", Minimal, "abc", Licence);

        Assert.Contains("namespace Rowles.LeanCorpus.Analysis.Stemmers.Snowball", result.Source, StringComparison.Ordinal);
        Assert.Contains("private static readonly SnowballAmong[] a_0 = new[]", result.Source, StringComparison.Ordinal);
        Assert.Contains("new SnowballAmong(\"a\", -1, 1)", result.Source, StringComparison.Ordinal);
        Assert.Contains("find_among_b(a_0);", result.Source, StringComparison.Ordinal);
        Assert.DoesNotContain("using System.Text;", result.Source, StringComparison.Ordinal);
        Assert.Contains("// Source: german.sbl (Snowball v3.2.0), SHA-256 abc.", result.Source, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("new Among(\"a\", -1, 1, 0)", "new Among(\"a\", -1, 1, 2)", "condition routine")]
    [InlineData("find_among_b(a_0, null);", "find_among_b(a_0, () => true);", "find_among")]
    [InlineData("return true;", "var b = new StringBuilder(); return true;", "StringBuilder")]
    [InlineData("return true;", "assign_to(null); return true;", "assign_to")]
    [InlineData("protected override bool stem()", "public bool stem()", "public member")]
    [InlineData("public partial class GermanStemmer : Stemmer", "public class GermanStemmer : Stemmer", "was not found")]
    [InlineData("// Generated from german.sbl", "// Generated from english.sbl", "first line")]
    public void UnrecognisedConstructs_AreRejected(string original, string replacement, string reason)
    {
        string source = Minimal.Replace(original, replacement, StringComparison.Ordinal);
        Assert.NotEqual(Minimal, source);

        var exception = Assert.Throws<SnowballTransformException>(() => SnowballTransform.Transform("german", source, "abc", Licence));
        Assert.Contains(reason, exception.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void AlteredReference_FailsItsPinnedHash()
    {
        string root = RepositoryTemporaryStorage.NewPath("devops-tests", "snowball-hash-");
        var source = new SnowballWorkspace(FindRepositoryRoot());
        CopyDirectory(source.FixtureRoot, Path.Combine(root, "src", "devops", "tests", "fixtures", "snowball"));
        var copy = new SnowballWorkspace(root);
        Directory.CreateDirectory(copy.SnowballSourceRoot);
        File.Copy(source.VersionsPath, copy.VersionsPath);
        string german = Path.Combine(copy.FixtureRoot, "reference", "Algorithms", "germanStemmer.generated.cs");
        File.AppendAllText(german, "// edited\n");

        var exception = Assert.Throws<InvalidDataException>(() => copy.Plan(AnalysisVersionRequests.None));
        Assert.Contains("germanStemmer.generated.cs", exception.Message, StringComparison.Ordinal);
    }

    private static void CopyDirectory(string source, string destination)
    {
        foreach (var directory in Directory.EnumerateDirectories(source, "*", SearchOption.AllDirectories))
            Directory.CreateDirectory(directory.Replace(source, destination, StringComparison.Ordinal));
        Directory.CreateDirectory(destination);
        foreach (var file in Directory.EnumerateFiles(source, "*", SearchOption.AllDirectories))
            File.Copy(file, file.Replace(source, destination, StringComparison.Ordinal));
    }

    internal static string FindRepositoryRoot()
    {
        for (var current = new DirectoryInfo(AppContext.BaseDirectory); current is not null; current = current.Parent)
        {
            if (File.Exists(Path.Combine(current.FullName, "src", "devops", "tests", "fixtures", "snowball", "manifest.json")))
                return current.FullName;
        }
        throw new DirectoryNotFoundException("Could not find the LeanCorpus repository from the test directory.");
    }
}
