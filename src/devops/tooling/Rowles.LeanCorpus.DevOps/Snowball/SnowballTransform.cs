using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace Rowles.LeanCorpus.DevOps.Snowball;

/// <summary>
/// Converts one unchanged Snowball 3.2.0 C# reference algorithm into the internal production class
/// that runs on <c>SnowballRuntime</c>. Only the rewrites listed in the #122 port plan are applied;
/// any construct the transform does not recognise fails the conversion rather than being adapted.
/// </summary>
internal static partial class SnowballTransform
{
    /// <summary>Bumped whenever the rewrites change, so regenerated output records how it was made.</summary>
    public const string TransformVersion = "1";

    public const string ProductionNamespace = "Rowles.LeanCorpus.Analysis.Stemmers.Snowball";

    private const string Indent = "        ";

    /// <summary>Returns the production class name for a Snowball algorithm, such as <c>GermanSnowballAlgorithm</c>.</summary>
    public static string ClassName(string algorithm)
        => string.Concat(char.ToUpperInvariant(algorithm[0]).ToString(), algorithm[1..], "SnowballAlgorithm");

    /// <summary>Transforms <paramref name="reference"/> and returns the production source.</summary>
    /// <param name="algorithm">The Snowball algorithm name, such as <c>german</c>.</param>
    /// <param name="reference">The unchanged reference C# generated by the Snowball compiler.</param>
    /// <param name="sblSha256">SHA-256 of the algorithm's <c>.sbl</c> source, recorded in the header.</param>
    /// <param name="licence">The Snowball BSD licence text, reproduced in the header.</param>
    public static SnowballTransformResult Transform(string algorithm, string reference, string sblSha256, string licence)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(algorithm);
        ArgumentNullException.ThrowIfNull(reference);

        var lines = reference.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n').ToList();
        string expectedFirst = $"// Generated from {algorithm}.sbl by Snowball 3.2.0 - https://snowballstem.org/";
        if (lines.Count == 0 || !string.Equals(lines[0].TrimStart('﻿'), expectedFirst, StringComparison.Ordinal))
            throw Reject(algorithm, 1, $"expected the first line '{expectedFirst}'");

        string referenceClass = string.Concat(char.ToUpperInvariant(algorithm[0]).ToString(), algorithm[1..], "Stemmer");
        string productionClass = ClassName(algorithm);
        var counts = new SnowballRewriteCounts();
        var stateFields = new List<(string Type, string Name)>();
        bool sawNamespace = false, sawClass = false, sawSlice = false;
        var output = new List<string>(lines.Count + 16);

        for (int index = 0; index < lines.Count; index++)
        {
            string line = lines[index];
            int lineNumber = index + 1;

            if (line == "namespace Snowball")
            {
                output.Add("namespace " + ProductionNamespace);
                sawNamespace = true;
                counts.Namespace++;
                continue;
            }

            if (line == "    using System.Text;")
            {
                counts.Usings++;
                continue;
            }

            if (line == $"    public partial class {referenceClass} : Stemmer")
            {
                output.Add($"    internal sealed class {productionClass} : SnowballRuntime");
                sawClass = true;
                counts.ClassDeclaration++;
                continue;
            }

            if (AmongArrayDeclaration().Match(line) is { Success: true } array)
            {
                output.Add($"{Indent}private static readonly SnowballAmong[] {array.Groups["name"].Value} = new[]");
                counts.AmongTables++;
                continue;
            }

            if (AmongEntry().Match(line) is { Success: true } entry)
            {
                if (entry.Groups["condition"].Value != "0")
                    throw Reject(algorithm, lineNumber, "an among entry has a condition routine, which the production runtime does not support");
                output.Add($"{entry.Groups["indent"].Value}new SnowballAmong({entry.Groups["args"].Value}){entry.Groups["tail"].Value}");
                counts.AmongEntries++;
                continue;
            }

            if (line == $"{Indent}private StringBuilder S_ch = new StringBuilder();")
            {
                output.Add($"{Indent}private readonly SnowballSlice S_ch = new();");
                stateFields.Add(("SnowballSlice", "S_ch"));
                sawSlice = true;
                counts.Slices++;
                continue;
            }

            if (StateField().Match(line) is { Success: true } field)
            {
                stateFields.Add((field.Groups["type"].Value, field.Groups["name"].Value));
                output.Add(line);
                continue;
            }

            string rewritten = line;
            rewritten = FindAmongCall().Replace(rewritten, match =>
            {
                counts.FindAmongCalls++;
                return $"{match.Groups["call"].Value}({match.Groups["table"].Value})";
            });
            if (CountOccurrences(rewritten, "find_among") != ProductionFindAmong().Count(rewritten))
                throw Reject(algorithm, lineNumber, "find_among is called with a condition callback or an unexpected argument");

            if (rewritten.Contains("current.Length", StringComparison.Ordinal))
            {
                counts.CurrentLength += CountOccurrences(rewritten, "current.Length");
                rewritten = rewritten.Replace("current.Length", "CurrentLength", StringComparison.Ordinal);
            }

            if (sawSlice && rewritten.Contains("S_ch.ToString()", StringComparison.Ordinal))
            {
                counts.Slices++;
                rewritten = rewritten.Replace("S_ch.ToString()", "S_ch", StringComparison.Ordinal);
            }

            output.Add(rewritten);
        }

        if (!sawNamespace)
            throw Reject(algorithm, 0, "the 'namespace Snowball' declaration was not found");
        if (!sawClass)
            throw Reject(algorithm, 0, $"the declaration 'public partial class {referenceClass} : Stemmer' was not found");

        if (stateFields.Count > 0)
            InsertResetState(algorithm, output, productionClass, stateFields);

        string body = string.Join('\n', output);
        RejectForbidden(algorithm, body);
        string bodySha256 = Sha256(body);
        string header = Header(algorithm, sblSha256, licence);
        return new SnowballTransformResult(productionClass, header + body, bodySha256, counts);
    }

    /// <summary>Returns the SHA-256 of the generated body, ignoring its header, from a production file.</summary>
    public static string BodySha256(string production)
    {
        int start = production.IndexOf("// Generated from ", StringComparison.Ordinal);
        if (start < 0)
            throw new InvalidDataException("The file is not a transformed Snowball algorithm.");
        return Sha256(production[start..].Replace("\r\n", "\n", StringComparison.Ordinal));
    }

    private static void InsertResetState(
        string algorithm, List<string> output, string productionClass, List<(string Type, string Name)> fields)
    {
        int classLine = output.FindIndex(line => line.EndsWith($"class {productionClass} : SnowballRuntime", StringComparison.Ordinal));
        int open = classLine + 1;
        if (classLine < 0 || open >= output.Count || output[open] != "    {")
            throw Reject(algorithm, 0, "the class body could not be located to add ResetState");

        var reset = new List<string>
        {
            $"{Indent}/// <summary>Clears per-word state held in fields, so each word starts as on a new instance.</summary>",
            $"{Indent}protected override void ResetState()",
            $"{Indent}{{",
        };
        foreach (var (type, name) in fields)
        {
            reset.Add(type switch
            {
                "int" => $"{Indent}    {name} = 0;",
                "bool" => $"{Indent}    {name} = false;",
                "SnowballSlice" => $"{Indent}    {name}.Clear();",
                _ => throw Reject(algorithm, 0, $"state field {name} has the unsupported type {type}"),
            });
        }
        reset.Add($"{Indent}}}");
        reset.Add(string.Empty);
        output.InsertRange(open + 1, reset);
    }

    private static void RejectForbidden(string algorithm, string body)
    {
        string[] forbidden =
        [
            "StringBuilder", "Func<", "Buffer", "Current", "assign_to", "copy_from", "replace_s",
            "new Among(", "Among[]", ", null)", ": Stemmer",
        ];
        foreach (var token in forbidden)
        {
            int at = token switch
            {
                "Current" => CurrentWord().Match(body) is { Success: true } match ? match.Index : -1,
                "Among[]" => BareAmongArray().Match(body) is { Success: true } match ? match.Index : -1,
                _ => body.IndexOf(token, StringComparison.Ordinal),
            };
            if (at >= 0)
                throw Reject(algorithm, LineOf(body, at), $"the output still contains '{token}'");
        }

        if (CurrentField().Match(body) is { Success: true } current)
            throw Reject(algorithm, LineOf(body, current.Index), "the output still uses the reference 'current' buffer");
        if (PublicMember().Match(body) is { Success: true } exposed)
            throw Reject(algorithm, LineOf(body, exposed.Index), "the output still declares a public member");
    }

    private static string Header(string algorithm, string sblSha256, string licence)
    {
        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("// Do not edit. Regenerate with './devops snowball generate'.\n");
        builder.Append($"// Source: {algorithm}.sbl (Snowball v3.2.0), SHA-256 {sblSha256}.\n");
        builder.Append($"// Transformed from the unchanged Snowball C# output by SnowballTransform version {TransformVersion}.\n");
        builder.Append("//\n");
        foreach (var line in licence.Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd('\n').Split('\n'))
            builder.Append(line.Length == 0 ? "//\n" : "// " + line + "\n");
        builder.Append('\n');
        return builder.ToString();
    }

    private static SnowballTransformException Reject(string algorithm, int line, string reason)
        => new($"Snowball transform rejected {algorithm} (line {line}): {reason}.");

    private static int LineOf(string text, int index) => text.AsSpan(0, index).Count('\n') + 1;

    private static int CountOccurrences(string text, string token)
    {
        int count = 0;
        for (int at = text.IndexOf(token, StringComparison.Ordinal); at >= 0; at = text.IndexOf(token, at + token.Length, StringComparison.Ordinal))
            count++;
        return count;
    }

    internal static string Sha256(string text) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)));

    [GeneratedRegex(@"^        private static readonly Among\[\] (?<name>a_\d+) = new\[\]$", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex AmongArrayDeclaration();

    [GeneratedRegex(@"^(?<indent>\s+)new Among\((?<args>""(?:[^""\\]|\\.)*"", -?\d+, -?\d+), (?<condition>-?\d+)\)(?<tail>,?)$", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex AmongEntry();

    [GeneratedRegex(@"^        private (?<type>int|bool) (?<name>[IB]_\w+);$", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex StateField();

    [GeneratedRegex(@"(?<call>find_among(?:_b)?)\((?<table>a_\d+), null\)", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex FindAmongCall();

    [GeneratedRegex(@"find_among(?:_b)?\(a_\d+\)", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex ProductionFindAmong();

    [GeneratedRegex(@"\bCurrent\b", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex CurrentWord();

    [GeneratedRegex(@"(?<!Snowball)Among\[\]", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex BareAmongArray();

    [GeneratedRegex(@"\bcurrent\b(?!Length)", RegexOptions.None, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex CurrentField();

    [GeneratedRegex(@"^\s*public\s", RegexOptions.Multiline, RegexMatchTimeoutPolicy.MatchTimeoutMilliseconds)]
    private static partial Regex PublicMember();
}

/// <summary>The production source for one algorithm.</summary>
/// <param name="ClassName">The internal class name.</param>
/// <param name="Source">The complete file, header included.</param>
/// <param name="BodySha256">SHA-256 of the generated body without the header, used for identity decisions.</param>
/// <param name="Counts">How many times each listed rewrite applied.</param>
internal sealed record SnowballTransformResult(string ClassName, string Source, string BodySha256, SnowballRewriteCounts Counts);

/// <summary>How many times each listed rewrite applied.</summary>
internal sealed class SnowballRewriteCounts
{
    public int Namespace { get; set; }
    public int Usings { get; set; }
    public int ClassDeclaration { get; set; }
    public int AmongTables { get; set; }
    public int AmongEntries { get; set; }
    public int FindAmongCalls { get; set; }
    public int CurrentLength { get; set; }
    public int Slices { get; set; }
}

/// <summary>The reference source contains a construct the transform does not support.</summary>
internal sealed class SnowballTransformException(string message) : Exception(message);
