using System.IO.Compression;
using Rowles.LeanCorpus.Codecs.StoredFields;
using Rowles.LeanCorpus.Document;
using Rowles.LeanCorpus.Document.Fields;
using Rowles.LeanCorpus.Index.Indexer;
using Rowles.LeanCorpus.Search;
using Rowles.LeanCorpus.Search.Queries;
using Rowles.LeanCorpus.Search.Searcher;
using Rowles.LeanCorpus.Store;

namespace Rowles.LeanCorpus.Tests.BrowserApp;

/// <summary>Trusted test fixtures shared by the desktop host and browser client.</summary>
public static class BrowserFixture
{
    /// <summary>The desktop host supplies its validated repository temporary-storage root.</summary>
    public static string? DesktopTemporaryRoot { get; set; }

    public static byte[] Create()
    {
        string path = NewPath();
        try
        {
            using (var directory = new MMapDirectory(path))
            using (var writer = new IndexWriter(directory, new IndexWriterConfig
            {
                DurableCommits = false, IndexingConcurrency = 1, MaxBufferedDocs = 2,
                MergePolicy = NoMergePolicy.Instance, UseCompoundFile = true,
                CompressionPolicy = FieldCompressionPolicy.Deflate, BuildHnswOnFlush = true
            }))
            {
                writer.AddDocuments(new[] { Make("one", "quick brown fox", 1), Make("two", "quick blue hare", 2), Make("three", "slow brown bear", 3) });
                writer.Commit();
            }
            using var output = new MemoryStream();
            ZipFile.CreateFromDirectory(path, output);
            return output.ToArray();
        }
        finally { if (Directory.Exists(path)) Directory.Delete(path, recursive: true); }
    }

    public static void Verify(byte[] archive)
    {
        string path = NewPath();
        try
        {
            // Only fixtures generated by this test assembly are accepted here. This is not a public importer.
            using (var input = new MemoryStream(archive)) ZipFile.ExtractToDirectory(input, path);
            using var directory = new MMapDirectory(path);
            using var historical = new IndexSearcher(directory);
            CheckQueries(historical, 2);
            using (var writer = new IndexWriter(directory, new IndexWriterConfig
            {
                DurableCommits = false, IndexingConcurrency = 1, MergePolicy = NoMergePolicy.Instance
            }))
            {
                writer.DeleteDocuments(new TermQuery("id", "two"));
                writer.Commit();
                writer.ForceMerge(1);
                writer.Commit();
            }
            using var latest = new IndexSearcher(directory);
            CheckQueries(latest, 1);
            CheckQueries(historical, 2);
        }
        finally { if (Directory.Exists(path)) Directory.Delete(path, recursive: true); }
    }

    private static void CheckQueries(IndexSearcher reader, int expected)
    {
        var term = reader.Search(new TermQuery("body", "quick"), 10);
        Require(term.TotalHits == expected && term.ScoreDocs.All(hit => float.IsFinite(hit.Score)), "Term count or score");
        Require(reader.Search(new PhraseQuery("body", "quick", "brown"), 10).TotalHits == 1, "Phrase count");
        var boolean = new BooleanQuery.Builder().Add(new TermQuery("body", "quick"), Occur.Must)
            .Add(new TermQuery("body", "hare"), Occur.MustNot).Build();
        Require(reader.Search(boolean, 10).TotalHits == 1, "Boolean count");
        Require(reader.Search(new RangeQuery("number", 1, 1), 10).TotalHits == 1, "Numeric range");
        var vector = reader.Search(new VectorQuery("embedding", new float[] { 1, 0, 0 }, topK: 1), 10);
        Require(vector.TotalHits == 1 && reader.GetStoredFields(vector.ScoreDocs[0].DocId)["id"][0] == "one", "Vector nearest neighbour and stored ID");
    }

    private static LeanDocument Make(string id, string body, int number)
    {
        var document = new LeanDocument();
        document.Add(new StringField("id", id));
        document.Add(new TextField("body", body));
        document.Add(new NumericField("number", number));
        document.Add(new VectorField("embedding", number == 1 ? new float[] { 1, 0, 0 } : number == 2 ? new float[] { 0, 1, 0 } : new float[] { 0, 0, 1 }));
        return document;
    }

    private static string NewPath()
    {
        string root = OperatingSystem.IsBrowser() ? "/leancorpus-tests"
            : DesktopTemporaryRoot ?? throw new InvalidOperationException("The fixture host must configure repository temporary storage.");
        return Path.Combine(root, "fixture-" + Guid.NewGuid().ToString("N"));
    }
    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException("Cross-host fixture: " + message);
    }
}
